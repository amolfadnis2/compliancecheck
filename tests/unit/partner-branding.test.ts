import { describe, it, expect, beforeAll } from 'vitest'
import { buildSampleReport } from '@/lib/pdf/sample-report-fixtures'
import { generateUnifiedReportBytes } from '@/lib/pdf/unified-report-generator'
import { generateAutoDealerPdfForRow, type AutoDealerRow } from '@/lib/pdf/auto-dealer-report'
import { withPreparedBy } from '@/lib/partner/report-branding'
import { parsePreparedBy, type PreparedBy } from '@/lib/partner/types'
import { resolvePartnerSubmission, parsePartnerBody } from '@/lib/partner/persist-preparer'
import { isAllowedLogoUrl } from '@/lib/partner/logo'
import { partnerEmailHtml, partnerFromAddress } from '@/lib/partner/email'
import { adaptStatutoryHealth, adaptPOSHRow } from '@/lib/pdf/report-data-adapter'
import { ASSESSMENT_TYPES } from '@/lib/constants/assessment-types'

/**
 * Partner mode: a CA / CS / lawyer / consultant fills in a paid assessment for
 * a client and the report carries their branding. These tests guard the two
 * promises: a normal report is unchanged, and a branded one shows the firm
 * (ASCII-clean, since jsPDF's Helvetica cannot render anything else).
 */

const PARTNER: PreparedBy = {
  firmName: 'Rao & Associates',
  preparerName: 'Asha Rao',
  designation: 'CA',
  email: 'asha@raoassociates.in',
  phone: '9876543210',
  city: 'Pune',
  brandColor: '#0F766E',
}

// jsPDF writes uncompressed content streams by default, so drawn text is
// searchable in the raw bytes.
const pdfText = (bytes: Uint8Array) => Buffer.from(bytes).toString('latin1')

function sample() {
  const report = buildSampleReport(ASSESSMENT_TYPES.STATUTORY_HEALTH)
  if (!report) throw new Error('missing statutory health sample')
  return { ...report, isSample: false }
}

describe('partner branding — unified report', () => {
  let plain: string
  let branded: string

  beforeAll(() => {
    plain = pdfText(generateUnifiedReportBytes(sample()))
    branded = pdfText(generateUnifiedReportBytes(withPreparedBy(sample(), PARTNER)))
  })

  it('leaves a normal report on ComplianceCheck branding', () => {
    expect(plain).toContain('(ComplianceCheck)')
    expect(plain).toContain('Pay-as-you-go Compliance Assessments for Indian SMEs')
    expect(plain).toContain('Generated by ComplianceCheck.co.in | This report does not constitute legal advice')
    expect(plain).toContain('Schedule Your Next Assessment')
    expect(plain).not.toContain('Prepared By')
    expect(plain).not.toContain('Powered by ComplianceCheck')
  })

  it('puts the firm on the cover, footer, closing box and disclaimer', () => {
    expect(branded).toContain('Rao & Associates')
    expect(branded).toContain('Prepared By')
    expect(branded).toContain('Asha Rao, CA')
    expect(branded).toContain('Prepared by Rao & Associates | Powered by ComplianceCheck.co.in')
    expect(branded).toContain('Contact Rao & Associates')
    expect(branded).toContain('self-declared')
    expect(branded).not.toContain('Pay-as-you-go Compliance Assessments for Indian SMEs')
    expect(branded).not.toContain('Generated by ComplianceCheck.co.in')
  })

  it('strips non-ASCII from partner text', () => {
    const bytes = generateUnifiedReportBytes(
      withPreparedBy(sample(), { ...PARTNER, firmName: 'Rao – Associates ₹ “Pune”' })
    )
    const text = pdfText(bytes)
    expect(text).toContain('Rao - Associates Rs. "Pune"')
  })

  it('names the file after the firm and client', () => {
    const report = withPreparedBy(sample(), PARTNER)
    expect(report.config.filenamePrefix).toMatch(/^Rao-Associates-/)
    expect(report.config.filenamePrefix).not.toContain('ComplianceCheck')
    expect(withPreparedBy(sample(), null).config.filenamePrefix).toBe(sample().config.filenamePrefix)
  })
})

describe('partner branding — adapters', () => {
  it('picks prepared_by up from a DB row and ignores junk', () => {
    const row = { id: 'x', assessment_type: 'statutory_health', overall_score: 50, responses: { answers: {} } }
    expect(adaptStatutoryHealth({ ...row, prepared_by: PARTNER }).preparedBy?.firmName).toBe('Rao & Associates')
    expect(adaptStatutoryHealth({ ...row, prepared_by: { firmName: 'x' } }).preparedBy).toBeUndefined()
    expect(adaptStatutoryHealth(row).preparedBy).toBeUndefined()
  })

  it('brands POSH rows too', () => {
    const report = adaptPOSHRow({ id: 'p1', overall_score: 40, risk_level: 'high', prepared_by: PARTNER })
    expect(report.preparedBy?.firmName).toBe('Rao & Associates')
  })
})

describe('partner branding — auto dealer report', () => {
  const row: AutoDealerRow = {
    id: '11111111-2222-3333-4444-555555555555',
    user_email: 'asha@raoassociates.in',
    email_verified: true,
    full_name: 'Asha Rao',
    company_name: 'Krishna Motors',
    phone: '9876543210',
    responses: {},
    price_tier: null,
    labour_regime: 'new',
    payment_status: 'paid',
  }

  it('is unchanged without a partner and branded with one', () => {
    const plain = pdfText(generateAutoDealerPdfForRow(row))
    expect(plain).toContain('(ComplianceCheck)')
    expect(plain).not.toContain('Prepared By')

    const branded = pdfText(generateAutoDealerPdfForRow({ ...row, prepared_by: PARTNER }))
    expect(branded).toContain('Prepared By')
    expect(branded).toContain('Prepared by Rao & Associates | Powered by ComplianceCheck.co.in')
    expect(branded).not.toContain('Generated by ComplianceCheck.co.in')
  })
})

describe('partner submission parsing', () => {
  it('treats missing or invalid partner data as a normal self-submission', async () => {
    expect((await resolvePartnerSubmission(null, {})).columns).toEqual({})
    expect((await resolvePartnerSubmission(null, { submissionMode: 'partner_on_behalf', preparedBy: { firmName: 'x' } })).columns).toEqual({})
    expect(parsePartnerBody({ submissionMode: 'self', preparedBy: PARTNER })).toBeNull()
  })

  it('stores a snapshot for a valid partner submission', async () => {
    const result = await resolvePartnerSubmission(null, { submissionMode: 'partner_on_behalf', preparedBy: PARTNER })
    expect(result.columns.submission_mode).toBe('partner_on_behalf')
    expect(result.columns.prepared_by?.firmName).toBe('Rao & Associates')
    expect(result.preparerId).toBeNull()
  })

  it('rejects bad designations, colours and logo URLs', () => {
    expect(parsePreparedBy({ ...PARTNER, designation: 'Wizard' })).toBeNull()
    expect(parsePreparedBy({ ...PARTNER, brandColor: 'red' })).toBeNull()
    expect(parsePreparedBy({ ...PARTNER, logoUrl: 'https://evil.example/logo.png' })).toBeNull()
  })
})

describe('partner logo URL allow-list', () => {
  it('only fetches from this project’s report-logos bucket', () => {
    const prev = process.env.NEXT_PUBLIC_SUPABASE_URL
    process.env.NEXT_PUBLIC_SUPABASE_URL = 'https://proj.supabase.co'
    try {
      expect(isAllowedLogoUrl('https://proj.supabase.co/storage/v1/object/public/report-logos/a.png')).toBe(true)
      expect(isAllowedLogoUrl('https://other.supabase.co/storage/v1/object/public/report-logos/a.png')).toBe(false)
      expect(isAllowedLogoUrl('http://169.254.169.254/storage/v1/object/public/report-logos/a.png')).toBe(false)
      expect(isAllowedLogoUrl('https://proj.supabase.co/storage/v1/object/public/report-logos/../secret')).toBe(false)
      expect(isAllowedLogoUrl(undefined)).toBe(false)
    } finally {
      process.env.NEXT_PUBLIC_SUPABASE_URL = prev
    }
  })
})

describe('partner email', () => {
  it('escapes partner-entered text and keeps our sending address', () => {
    const html = partnerEmailHtml({
      preparedBy: { ...PARTNER, firmName: '<script>alert(1)</script>' },
      reportLabel: 'Statutory Compliance Health Check',
      companyName: 'Acme',
      score: 0,
      status: 'Non-Compliant',
      statusColour: '#DC2626',
    })
    expect(html).not.toContain('<script>')
    expect(html).toContain('&lt;script&gt;')
    expect(html).toContain('Powered by ComplianceCheck.co.in')
    expect(html).toContain('>0%<')

    expect(partnerFromAddress('ComplianceCheck <noreply@compliancecheck.co.in>', 'Rao "&" Co')).toBe(
      '"Rao & Co via ComplianceCheck" <noreply@compliancecheck.co.in>'
    )
  })
})
