      doc.setFillColor(...sevColor)
      doc.rect(ML, y, badgeW, 6, 'F')
      doc.setFontSize(7)
      doc.setFont('helvetica', 'bold')
      doc.setTextColor(...C.white)
      doc.text(gap.severity.toUpperCase(), ML + 2, y + 4.5)

      // Phase tag
