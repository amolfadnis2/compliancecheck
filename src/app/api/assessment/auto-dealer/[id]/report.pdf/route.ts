  doc.rect(ML + bw + 5, y, bw, 28, 'F')
  doc.setFontSize(9)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(...C.white)
  doc.text('Risk Level', ML + bw + 8, y + 6)
  doc.setFontSize(14)
  doc.text(riskText, ML + bw + 8, y + 20)
  y += 36

  // Key stats row
