export { cleanText };

function getScoreColor(score: number): [number, number, number] {
  if (score >= 90) return COLORS.success;
  if (score >= 70) return COLORS.warning;
  return COLORS.danger;
}

function getPriorityColor(priority: string): [number, number, number] {
  switch (priority) {
    case 'high':
      return COLORS.danger;
    case 'medium':
      return COLORS.warning;
    case 'low':
      return COLORS.success;
    default:
      return COLORS.textLight;
  }
}

function formatDate(date: Date): string {
  return date.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  });
}

function checkPageBreak(doc: jsPDF, currentY: number, requiredHeight: number): number {
  const pageHeight = doc.internal.pageSize.getHeight();
  if (currentY + requiredHeight > pageHeight - MARGIN_BOTTOM) {
    doc.addPage();
    return MARGIN_TOP;
  }
  return currentY;
}

function addPageHeader(doc: jsPDF, companyName: string, pageNum: number): void {
  const pageWidth = doc.internal.pageSize.getWidth();
  doc.setFontSize(FONTS.tiny);
  doc.setTextColor(...COLORS.textLight);
  doc.text(cleanText(companyName), MARGIN_LEFT, 10);
  doc.text(`Page ${pageNum}`, pageWidth - MARGIN_RIGHT, 10, { align: 'right' });
}

function addPageFooter(doc: jsPDF): void {
  const pageHeight = doc.internal.pageSize.getHeight();
  doc.setFontSize(FONTS.tiny);
  doc.setTextColor(...COLORS.textLight);
  const footerText = 'Generated by ComplianceCheck.co.in | This report does not constitute legal advice';
  doc.text(footerText, MARGIN_LEFT, pageHeight - MARGIN_BOTTOM + 5);
}

/**
 * Page-break helper for sections that span pages: when `height` will not fit,
 * close the current page with its footer, start a new one with its header, and
 * return the new y. `page` is mutated so callers keep correct page numbers.
 */
function ensureSpace(
  doc: jsPDF,
  currentY: number,
  height: number,
  companyName: string,
  page: { num: number }
): number {
  if (currentY + height <= doc.internal.pageSize.getHeight() - MARGIN_BOTTOM) return currentY;
  addPageFooter(doc);
  doc.addPage();
  page.num++;
  addPageHeader(doc, companyName, page.num);
  return 20;
}

function isUrl(value: string | undefined): value is string {
  return !!value && /^https?:\/\/\S+$/i.test(value.trim());
}

/**
 * Print "<label>: <value>" — the value is a clickable link when it is a URL,
 * plain text otherwise (some rules name a department rather than a portal).
 * Returns the height used.
 */
function drawLinkLine(doc: jsPDF, label: string, value: string, x: number, y: number, width: number): number {
  const prefix = `${label}: `;
  doc.setTextColor(...COLORS.textLight);
  doc.text(prefix, x, y);
  const prefixWidth = doc.getTextWidth(prefix);
  const text = cleanText(value.trim());
  if (isUrl(value)) {
    doc.setTextColor(...COLORS.primary);
    const shown = doc.splitTextToSize(text, width - prefixWidth)[0] as string;
    doc.textWithLink(shown, x + prefixWidth, y, { url: value.trim() });
    doc.setTextColor(...COLORS.text);
    return 4;
  }
  const lines = doc.splitTextToSize(text, width - prefixWidth);
  doc.text(lines, x + prefixWidth, y);
  doc.setTextColor(...COLORS.text);
  return lines.length * 4;
}

function drawLine(
  doc: jsPDF,
  x1: number,
  y: number,
  x2: number,
  color: [number, number, number] = COLORS.lightGray
): void {
  doc.setDrawColor(...color);
  doc.setLineWidth(0.5);
  doc.line(x1, y, x2, y);
}

